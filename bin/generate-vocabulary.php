<?php

/**
 * Writes src/Type/Vocabulary.php from schema.org's published definitions.
 *
 * Download the release's JSON-LD file (https://schema.org/version/latest/schemaorg-current-https.jsonld)
 * and run:
 *
 *     php bin/generate-vocabulary.php path/to/schemaorg-current-https.jsonld 30.1
 *
 * A third argument writes the vocabulary somewhere else, as the tests do.
 *
 * The vocabulary keeps every type an organisation can be (schema:Organization and its subtypes, the
 * types they extend, and Place, for local businesses), outside the pending area, and the domains of
 * the properties a business or office is described with.
 */

declare(strict_types=1);

const PROPERTIES = [
    'acceptsReservations', 'additionalType', 'address', 'contactPoint', 'department', 'email', 'geo',
    'hasMenu', 'legalName', 'location', 'logo', 'openingHoursSpecification', 'parentOrganization',
    'priceRange', 'sameAs', 'servesCuisine', 'starRating', 'taxID', 'telephone',
];

[, $source, $version, $target] = $argv + [null, null, null, __DIR__ . '/../src/Type/Vocabulary.php'];
if (! is_string($source) || ! is_string($version) || ! is_file($source)) {
    fwrite(STDERR, "usage: php bin/generate-vocabulary.php schemaorg-current-https.jsonld VERSION [TARGET]\n");
    exit(1);
}

$graph = json_decode((string) file_get_contents($source), true, flags: JSON_THROW_ON_ERROR)['@graph'];

$list  = static fn(mixed $value): array => is_array($value) && array_is_list($value) ? $value : (null === $value ? [] : [$value]);
$id    = static fn(mixed $node): string => is_array($node) ? (string) $node['@id'] : (string) $node;
$local = static fn(string $iri): string => str_starts_with($iri, 'schema:') ? substr($iri, 7) : '';

$parents    = [];
$deprecated = [];
$domains    = [];
foreach ($graph as $node) {
    $name = $local($id($node));
    if ('' === $name) {
        continue;
    }

    $areas = array_map($id, $list($node['schema:isPartOf'] ?? null));
    if (in_array('https://pending.schema.org', $areas, true) || in_array('https://meta.schema.org', $areas, true)) {
        continue;
    }

    $types = array_map($id, $list($node['@type'] ?? null));
    if (in_array('rdfs:Class', $types, true)) {
        $parents[$name] = array_values(array_filter(array_map(
            static fn(mixed $parent): string => $local($id($parent)),
            $list($node['rdfs:subClassOf'] ?? null),
        )));
        $comment = is_string($node['rdfs:comment'] ?? null) ? $node['rdfs:comment'] : '';
        if (isset($node['schema:supersededBy']) || 1 === preg_match('/\b(deprecated|was deprecated)\b/i', $comment)) {
            $deprecated[] = $name;
        }
    }

    if (in_array('rdf:Property', $types, true) && in_array($name, PROPERTIES, true)) {
        $domains[$name] = array_values(array_map(
            static fn(mixed $domain): string => $local($id($domain)),
            $list($node['schema:domainIncludes'] ?? null),
        ));
    }
}

$descends = static function (string $type, string $ancestor) use (&$descends, $parents): bool {
    if ($type === $ancestor) {
        return true;
    }

    foreach ($parents[$type] ?? [] as $parent) {
        if ($descends($parent, $ancestor)) {
            return true;
        }
    }

    return false;
};

$kept = [];
foreach (array_keys($parents) as $type) {
    if ($descends($type, 'Organization')) {
        $kept[$type] = true;
    }
}

$withAncestors = $kept;
$add           = static function (string $type) use (&$add, &$withAncestors, $parents): void {
    foreach ($parents[$type] ?? [] as $parent) {
        if (! isset($withAncestors[$parent])) {
            $withAncestors[$parent] = true;
            $add($parent);
        }
    }
};
foreach (array_keys($kept) as $type) {
    $add($type);
}

$types = array_intersect_key($parents, $withAncestors);
ksort($types);
sort($deprecated);
$deprecated = array_values(array_filter($deprecated, static fn(string $type): bool => isset($types[$type])));
ksort($domains);

$export = static function (array $value, int $depth = 1) use (&$export): string {
    $pad   = str_repeat('    ', $depth + 1);
    $lines = [];
    foreach ($value as $key => $item) {
        $prefix  = array_is_list($value) ? '' : var_export($key, true) . ' => ';
        $lines[] = $pad . $prefix . (is_array($item) ? $export($item, $depth + 1) : var_export($item, true)) . ',';
    }

    return [] === $lines ? '[]' : "[\n" . implode("\n", $lines) . "\n" . str_repeat('    ', $depth) . ']';
};

$php = <<<PHP
<?php

declare(strict_types=1);

namespace Contenir\Contact\Type;

/**
 * The schema.org types an organisation can be, and the types they extend, with each type's direct
 * parents; the types schema.org has deprecated; and the domains of the properties a business or
 * office is described with.
 *
 * Generated by bin/generate-vocabulary.php from schema.org {$version}. Don't edit it by hand.
 *
 * @internal
 */
final class Vocabulary
{
    public const string VERSION = '{$version}';

    /**
     * @var array<string, list<string>>
     */
    public const array TYPES = {$export($types)};

    /**
     * @var list<string>
     */
    public const array DEPRECATED = {$export($deprecated)};

    /**
     * @var array<string, list<string>>
     */
    public const array PROPERTIES = {$export($domains)};
}

PHP;

file_put_contents((string) $target, $php);
fwrite(STDOUT, sprintf("%d types, %d deprecated, %d properties\n", count($types), count($deprecated), count($domains)));
